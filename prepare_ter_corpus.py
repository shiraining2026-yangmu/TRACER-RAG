#!/usr/bin/env python3
"""Convert AEK builder output using an explicitly supplied split assignment.

This utility does not infer the private study split, clinical relevance or data
permissions. It rejects exact normalized-question overlap across splits.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path
import re


def read(path):
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def unique(rows, key):
    mapped = {}
    for row in rows:
        identifier = str(row.get(key, "")).strip()
        if not identifier or identifier in mapped:
            raise ValueError(f"Missing or duplicate {key}")
        mapped[identifier] = row
    return mapped


def prepare(applications, knowledge, edges, splits):
    apps, items = unique(applications, "application_id"), unique(knowledge, "knowledge_id")
    assignments = unique(splits, "application_id")
    if set(assignments) != set(apps):
        raise ValueError("Split manifest must cover exactly all application IDs")
    seen_questions = {}
    converted_apps = []
    for app_id, app in apps.items():
        split = assignments[app_id].get("split")
        if split not in {"build", "dev", "test"}:
            raise ValueError("Invalid split")
        question = str(app.get("question", "")).strip()
        normalized = re.sub(r"[\W_]+", "", question.lower())
        if not normalized or not str(app.get("answer", "")).strip():
            raise ValueError("Empty application question/answer")
        if normalized in seen_questions and seen_questions[normalized] != split:
            raise ValueError("Normalized-question overlap across splits")
        seen_questions[normalized] = split
        converted_apps.append({**app, "release": {**app.get("release", {}), "split": split}})
    edge_ids, build_edges, support = set(), [], {app_id: set() for app_id in apps}
    for edge in edges:
        edge_id = str(edge.get("e_id") or edge.get("edge_id") or "").strip()
        app_id, knowledge_id = edge.get("application_id"), edge.get("knowledge_id")
        if not edge_id or edge_id in edge_ids or app_id not in apps or knowledge_id not in items:
            raise ValueError("Missing/duplicate edge ID or unresolved A/K link")
        if edge.get("relation") not in {"diagnostic_support", "treatment_or_operation_support", "explanatory_support"}:
            raise ValueError("Unknown relation label")
        edge_ids.add(edge_id)
        support[app_id].add(knowledge_id)
        if assignments[app_id]["split"] == "build":
            build_edges.append({**edge, "e_id": edge_id})
    if not build_edges:
        raise ValueError("No Build evidence edges")
    queries = []
    for app_id, app in apps.items():
        if not support[app_id]:
            continue
        queries.append({"application_id": app_id, "sample_id": app_id,
                        "question": app["question"], "split": assignments[app_id]["split"],
                        "evaluation_knowledge_ids": sorted(support[app_id])})
    return converted_apps, list(items.values()), build_edges, queries


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--applications", type=Path, required=True)
    parser.add_argument("--knowledge", type=Path, required=True)
    parser.add_argument("--edges", type=Path, required=True)
    parser.add_argument("--splits", type=Path, required=True, help="CSV: application_id,split (build/dev/test)")
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    if args.output_dir.exists():
        raise FileExistsError(args.output_dir)
    with args.splits.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        if set(reader.fieldnames or []) != {"application_id", "split"}:
            raise ValueError("Split CSV columns must be application_id,split")
        splits = list(reader)
    converted = prepare(read(args.applications), read(args.knowledge), read(args.edges), splits)
    args.output_dir.mkdir(parents=True)
    names = ("applications.jsonl", "knowledge.jsonl", "build_edges.jsonl", "queries.jsonl")
    for name, rows in zip(names, converted):
        (args.output_dir / name).write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    manifest = {"version": "ter-explicit-split-conversion-v1", "input_sha256": {
        name: hashlib.sha256(getattr(args, name).read_bytes()).hexdigest()
        for name in ("applications", "knowledge", "edges", "splits")},
        "counts": dict(zip(names, map(len, converted))),
        "split_policy": "External explicit assignment; no random split generated by this utility",
        "evaluation_relevance": "Source A-K links, not independent expert clinical judgments"}
    (args.output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(manifest))


if __name__ == "__main__":
    main()

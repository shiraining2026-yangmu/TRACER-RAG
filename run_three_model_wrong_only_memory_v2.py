#!/usr/bin/env python3
"""Continue the frozen wrong-only experiment with unused CUDA cache released."""
from __future__ import annotations

import argparse
import contextlib
import json
from pathlib import Path
import signal
import subprocess
import sys

from benchmark_integrity import sha256
import run_three_model_wrong_only as original
from reuse_wrong_only_baselines import reuse_completed_baselines
from summarize_ter_wrong_only_memory_v2 import PROTOCOL, summarize

ADDITIONAL_CODE = ("run_three_model_wrong_only_memory_v2.py", "reuse_wrong_only_baselines.py",
    "serve_benchmark_memory_control.py", "preflight_wrong_only_memory_v2.py", "summarize_ter_wrong_only_memory_v2.py")


@contextlib.contextmanager
def version_bindings():
    # Reuse the frozen supervisor's implementation in a separate process. The
    # original files and its old-version standalone audit remain unchanged.
    names = ("PROTOCOL", "CODE", "MODELS", "summarize", "reuse_completed_baselines", "commit_manifest")
    saved = {name: getattr(original, name) for name in names}
    def commit(work, manifest):
        manifest["cuda_memory_policy"] = "release_after_request"
        saved["commit_manifest"](work, manifest)
    original.PROTOCOL = PROTOCOL
    original.CODE = (*saved["CODE"], *ADDITIONAL_CODE)
    original.MODELS = tuple(model for model in saved["MODELS"] if model[0] != "mistral_7b_instruct_v03")
    original.summarize = summarize
    original.reuse_completed_baselines = reuse_completed_baselines
    original.commit_manifest = commit
    try:
        yield
    finally:
        for name, value in saved.items():
            setattr(original, name, value)


class Supervisor(original.Supervisor):
    def __init__(self, app, output):
        super().__init__(app, output)
        self.baseline_source = app / "questionbank_eval/model_benchmarks/ter_wrong_only_batch4_v1"

    def serve(self, script, args, base, model_id, log):
        if script in {"serve_single_generator.py", "serve_qwen_critic_adapter.py"}:
            kind = "generator" if script == "serve_single_generator.py" else "critic"
            args = ["--service-kind", kind, "--memory-policy", "release_after_request", *args]
            script = "serve_benchmark_memory_control.py"
        return super().serve(script, args, base, model_id, log)

    def run(self, script, *args):
        script = {"preflight_wrong_only.py": "preflight_wrong_only_memory_v2.py",
                  "summarize_ter_wrong_only.py": "summarize_ter_wrong_only_memory_v2.py"}.get(script, script)
        return super().run(script, *args)

    def run_queue(self):
        old_work = self.baseline_source / "mistral_7b_instruct_v03"
        # Verify completed Mistral with its original code contract, without
        # relabelling its predictions as generated by the memory-fix version.
        subprocess.run([sys.executable, str(self.app / "summarize_ter_wrong_only.py"),
                        "--work-dir", str(old_work), "--slug", "mistral_7b_instruct_v03"],
                       check=True, stdout=subprocess.DEVNULL)
        reference = {"mistral_7b_instruct_v03": {"source_protocol": "ter-wrong-only-batch4-v1",
            "source_directory": str(old_work), "summary_sha256": sha256(old_work / "summary.json"),
            "manifest_sha256": sha256(old_work / "manifest.json"), "predictions_relabelled": False}}
        original.atomic_json(self.output / "completed_model_references.json", reference)
        super().run_queue()
        combined = {"mistral_7b_instruct_v03": json.loads((old_work / "summary.json").read_text())["arms"]}
        for slug, _, _ in original.MODELS:
            combined[slug] = json.loads((self.output / slug / "summary.json").read_text())["arms"]
        original.atomic_json(self.output / "all_models_summary.json", combined)
        self.work = self.output
        self.state("complete", "complete", completed_models=list(combined))


def main():
    import fcntl
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-root", type=Path)
    args = parser.parse_args()
    app = Path(__file__).resolve().parent
    output = args.output_root or app / "questionbank_eval/model_benchmarks/ter_wrong_only_batch4_memory_v2"
    output.mkdir(parents=True, exist_ok=True)
    with version_bindings(), (output / "supervisor.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        supervisor = Supervisor(app, output)
        def stop(signum, frame):
            raise original.StopRequested()
        signal.signal(signal.SIGTERM, stop)
        signal.signal(signal.SIGINT, stop)
        try:
            supervisor.run_queue()
        except original.StopRequested:
            signal.signal(signal.SIGTERM, signal.SIG_IGN)
            supervisor.state(supervisor.stage, "interrupted")
            supervisor.stop_servers()
            raise SystemExit(143)
        finally:
            supervisor.stop_servers()


if __name__ == "__main__":
    main()
